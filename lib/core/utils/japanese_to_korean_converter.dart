  /// 코퍼스·테스트용 — 문장 내 모든 한자에 읽기가 등록됐는지 확인.
  static ({String hiragana, bool complete}) readingCoverage(String text) =>
      _toHiraganaChecked(text);

  /// STT가 한자만 히라가나로 돌려준 경우 시뮬레이션 (가타카나·라틴 유지).
  static String simulateSttFromTarget(String text) {
    var work = JapaneseSttFixMap.apply(text.trim());
    for (final pair in _sortedPhraseReadings) {
      work = work.replaceAll(pair.$1, pair.$2);
    }

    final buffer = StringBuffer();
    var i = 0;
    while (i < work.length) {
      final ch = work[i];
      if (_punct.hasMatch(ch)) {
        buffer.write(ch);
        i++;
        continue;
      }
      if (_hiragana.hasMatch(ch) ||
          _katakana.hasMatch(ch) ||
          _latin.hasMatch(ch)) {
        buffer.write(ch);
        i++;
        continue;
      }
      if (_kanji.hasMatch(ch)) {
        var matched = false;
        for (final pair in _sortedPhraseReadings) {
          if (work.startsWith(pair.$1, i)) {
            buffer.write(pair.$2);
            i += pair.$1.length;
            matched = true;
            break;
          }
        }
        if (matched) continue;

        if (ch == _iterationMark && i > 0) {
          final prevReading = _kanjiReadings[work[i - 1]];
          if (prevReading != null) {
            buffer.write(prevReading);
            i++;
            continue;
          }
        }

        final reading = _kanjiReadings[ch];
        if (reading != null) {
          buffer.write(reading);
        }
        i++;
        continue;
      }
      buffer.write(ch);
      i++;
    }
    return buffer.toString();
  }

  /// 미등록 한자 목록 (코퍼스 점검용).
  static Set<String> missingKanjiIn(String text) {
    final missing = <String>{};
    final kanji = RegExp(r'[\u4E00-\u9FFF\u3006\u3007\u303B]');
    for (final m in kanji.allMatches(text)) {
      final ch = m.group(0)!;
      if (ch == _iterationMark) continue;
      if (!readingCoverage(ch).complete) missing.add(ch);
    }
    return missing;
  }

  /// 1단계: 한자·가타카나 → 히라가나 (미등록 한자는 건너뛰고 계속).
  /// 미등록 한자가 있어도 최대한 이어붙인 결과 — 표시용이 아닌 내부 매칭용
  /// (예: [JapaneseReadingFold] 읽기 비교)으로만 사용할 것.
  static String toHiragana(String text) => _toHiraganaChecked(text).hiragana;

  /// [toHiragana]와 동일하되, 사전에 없는 한자를 만나면 [complete]가 false.
  /// 미등록 한자를 자동으로 뭉개고 남은 글자만 이어붙이면(예: `対応の怒` →
  /// `の`) 전혀 엉뚱한 발음처럼 보이는 거짓 힌트가 생기므로, 표시용
  /// 변환([transliterateOrNull])에서는 이 플래그로 실패를 구분해야 한다.
  static ({String hiragana, bool complete}) _toHiraganaChecked(String text) {
    var work = JapaneseSttFixMap.apply(text.trim());
    if (work.isEmpty) return (hiragana: '', complete: true);

    for (final pair in _sortedPhraseReadings) {
      work = work.replaceAll(pair.$1, pair.$2);
    }

    final buffer = StringBuffer();
    var complete = true;
    var i = 0;
    while (i < work.length) {
      final ch = work[i];
      if (_punct.hasMatch(ch)) {
        i++;
        continue;
      }

      if (_hiragana.hasMatch(ch)) {
        buffer.write(ch);
        i++;
        continue;
      }

      if (_katakana.hasMatch(ch)) {
        buffer.write(_katakanaToHiraganaChar(ch));
        i++;
        continue;
      }

      if (_kanji.hasMatch(ch)) {
        var matched = false;
        for (final pair in _sortedPhraseReadings) {
          if (work.startsWith(pair.$1, i)) {
            buffer.write(pair.$2);
            i += pair.$1.length;
            matched = true;
            break;
          }
        }
        if (matched) continue;

        // 々(반복부호) — 직전 한자와 같은 읽기를 반복 (예: 色々 → いろいろ).
        if (ch == _iterationMark && i > 0) {
          final prevReading = _kanjiReadings[work[i - 1]];
          if (prevReading != null) {
            buffer.write(prevReading);
            i++;
            continue;
          }
        }

        final reading = _kanjiReadings[ch];
        if (reading != null) {
          buffer.write(reading);
        } else {
          complete = false;
        }
        i++;
        continue;
      }

      i++;
    }

    return (hiragana: buffer.toString(), complete: complete);
  }

  /// 2단계: 히라가나 → 한글.
  static String toHangul(String hiragana) {
    if (hiragana.isEmpty) return '';
    return _kanaStringToHangul(hiragana);
  }

  /// STT 오답 텍스트 → 한글 발음. 변환 불가 시 `null`.
  ///
  /// 사전에 없는 한자가 섞여 있으면 그 글자만 건너뛰고 이어붙이지 않는다 —
  /// 예를 들어 `対応の怒`에서 `対応`/`怒`를 모르면 남은 `の`만으로 `노`라는
  /// 엉뚱한 부분 발음을 보여주는 대신, 전체를 변환 실패로 보고 `null`을
  /// 반환해 오해를 부르는 표시를 막는다.
  static String? transliterateOrNull(String text, {String language = 'Japanese'}) {
    if (language != 'Japanese') return null;
    final trimmed = text.trim();
    if (trimmed.isEmpty) return null;

    try {
      final result = _mixedScriptToHangul(trimmed);
      if (!result.complete) return null;
      if (result.hangul.isEmpty || _containsInvalidOutput(result.hangul)) {
        return null;
      }
      return result.hangul;
    } catch (_) {
      return null;
    }
  }

  /// 일본어·알파벳 혼합 문장 — 구간별 변환 후 이어 붙인다.
  static ({String hangul, bool complete}) _mixedScriptToHangul(String text) {
    final buffer = StringBuffer();
    var complete = true;
    var i = 0;
    while (i < text.length) {
      final ch = text[i];
      if (_punct.hasMatch(ch)) {
        i++;
        continue;
      }

      if (_latin.hasMatch(ch)) {
        var j = i;
        while (j < text.length && _latin.hasMatch(text[j])) {
          j++;
        }
        buffer.write(_latinRunToHangul(text.substring(i, j)));
        i = j;
        continue;
      }

      var j = i;
      while (j < text.length &&
          !_punct.hasMatch(text[j]) &&
          !_latin.hasMatch(text[j])) {
        j++;
      }
      final segment = text.substring(i, j);
      final checked = _toHiraganaChecked(segment);
      if (!checked.complete) complete = false;
      if (checked.hiragana.isNotEmpty) {
        buffer.write(toHangul(checked.hiragana));
      }
      i = j;
    }
    return (hangul: buffer.toString(), complete: complete);
  }

  static String _latinRunToHangul(String run) {
    if (run.isEmpty) return '';
    final upper = run.toUpperCase();

    final acronym = _acronymToHangul[upper];
    if (acronym != null) return acronym;

    final buffer = StringBuffer();
    for (var i = 0; i < upper.length; i++) {
      final mapped = _letterToHangul[upper[i]];
      if (mapped != null) buffer.write(mapped);
    }
    return buffer.toString();
  }

  static String _katakanaToHiraganaChar(String ch) {
    final code = ch.runes.first;
    if (code >= 0x30A1 && code <= 0x30F6) {
      return String.fromCharCode(code - 0x60);
    }
    if (code == 0x30FC) return 'ー';
    if (code == 0x30F3) return 'ん';
    if (code == 0x30C3) return 'っ';
    return ch;
  }

  static String _kanaStringToHangul(String hiragana) {
    final sortedKeys = _kanaToHangul.keys.toList()
      ..sort((a, b) => b.length.compareTo(a.length));

    final buffer = StringBuffer();
    var i = 0;
    while (i < hiragana.length) {
      if (hiragana[i] == 'ー') {
        _applyLongVowel(buffer);
        i++;
        continue;
      }

      if (hiragana[i] == 'っ') {
        final next = _readKanaSyllable(hiragana, i + 1, sortedKeys);
        if (next == null) return buffer.toString();
        buffer.write(_sokuonDouble[next.hangul] ?? next.hangul);
        i = next.nextIndex;
        continue;
      }

      final syllable = _readKanaSyllable(hiragana, i, sortedKeys);
      if (syllable == null) return buffer.toString();
      buffer.write(syllable.hangul);
      i = syllable.nextIndex;
    }

    return buffer.toString();
  }

  static void _applyLongVowel(StringBuffer buffer) {
    final text = buffer.toString();
    if (text.isEmpty) return;
    final lastChar = text[text.length - 1];
    const extendable = {'아', '이', '우', '에', '오', '와', '야', '유', '요'};
    if (extendable.contains(lastChar)) buffer.write(lastChar);
  }

  static ({String hangul, int nextIndex})? _readKanaSyllable(
    String text,
    int start,
    List<String> sortedKeys,
  ) {
    if (start >= text.length) return null;
    for (final key in sortedKeys) {
      if (text.startsWith(key, start)) {
        final hangul = _kanaToHangul[key];
        if (hangul == null) return null;
        return (hangul: hangul, nextIndex: start + key.length);
      }
    }
    return null;
  }

  static bool _containsInvalidOutput(String hangul) {
    return RegExp(r'[ぁ-んァ-ン一-龯A-Za-z]').hasMatch(hangul);
  }
